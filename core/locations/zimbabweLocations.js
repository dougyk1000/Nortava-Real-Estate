function norm(val) {
  return String(val || '').trim().toLowerCase();
}

export function getProvinces() {
  return ZIMBABWE_LOCATIONS.map(p => p.province);
}

export function getCitiesByProvince(province = '') {
  const cleanProv = norm(province);
  if (!cleanProv) {
    return ZIMBABWE_LOCATIONS.flatMap(p =>
      p.cities.map(c => ({ province: p.province, city: c.city }))
    );
  }
  const found = ZIMBABWE_LOCATIONS.find(p => norm(p.province) === cleanProv);
  return found ? found.cities.map(c => ({ province: found.province, city: c.city })) : [];
}

export function getZonesByCity(city = '', province = '') {
  const cleanCity = norm(city);
  const cleanProv = norm(province);
  if (!cleanCity) return [];

  for (const p of ZIMBABWE_LOCATIONS) {
    if (cleanProv && norm(p.province) !== cleanProv) continue;
    const foundCity = p.cities.find(c => norm(c.city) === cleanCity);
    if (foundCity) {
      return foundCity.zones.map(z => ({
        province: p.province,
        city: foundCity.city,
        zone: z.zone,
        areas: z.areas
      }));
    }
  }
  return [];
}

export function getAreas({ province = '', city = '', zone = '' } = {}) {
  const cleanProv = norm(province);
  const cleanCity = norm(city);
  const cleanZone = norm(zone);
  const results = [];

  for (const p of ZIMBABWE_LOCATIONS) {
    if (cleanProv && norm(p.province) !== cleanProv) continue;
    for (const c of p.cities) {
      if (cleanCity && norm(c.city) !== cleanCity) continue;
      for (const z of c.zones) {
        if (cleanZone && norm(z.zone) !== cleanZone) continue;
        for (const area of z.areas) {
          results.push({
            province: p.province,
            city: c.city,
            zone: z.zone,
            area
          });
        }
      }
    }
  }
  return results;
}

export function getLocationStats() {
  let cityCount = 0;
  let zoneCount = 0;
  let areaCount = 0;
  for (const p of ZIMBABWE_LOCATIONS) {
    cityCount += p.cities.length;
    for (const c of p.cities) {
      zoneCount += c.zones.length;
      for (const z of c.zones) {
        areaCount += z.areas.length;
      }
    }
  }
  return {
    provinces: ZIMBABWE_LOCATIONS.length,
    cities: cityCount,
    zones: zoneCount,
    areas: areaCount
  };
}

export function formatLocationLabel({ area = '', city = '', province = '', customDetail = '' } = {}) {
  const parts = [];
  if (customDetail && customDetail.trim()) parts.push(customDetail.trim());
  if (area && area.trim() && area !== '__other__') parts.push(area.trim());
  if (city && city.trim()) parts.push(city.trim());
  if (province && province.trim()) parts.push(province.trim());
  return parts.join(', ');
}

export function parseLocationString(locationStr = '') {
  const raw = String(locationStr || '').trim();
  const lower = raw.toLowerCase();
  const result = {
    province: '',
    city: '',
    zone: '',
    area: '',
    raw
  };

  if (!lower) return result;

  // Match area first (longest/most specific match)
  let bestMatch = null;
  for (const p of ZIMBABWE_LOCATIONS) {
    for (const c of p.cities) {
      for (const z of c.zones) {
        for (const areaName of z.areas) {
          const areaLower = areaName.toLowerCase();
          const bareAreaLower = areaLower.replace(/\s*\([^)]*\)\s*/g, '').trim();
          const cityLower = c.city.toLowerCase();
          const matchedExact = lower.includes(areaLower);
          const matchedBareWithCity = bareAreaLower && lower.includes(bareAreaLower) && lower.includes(cityLower);
          if (matchedExact || matchedBareWithCity) {
            const score = (matchedExact ? areaLower.length : bareAreaLower.length) + (lower.includes(cityLower) ? 100 : 0);
            if (!bestMatch || score > bestMatch.score) {
              bestMatch = { province: p.province, city: c.city, zone: z.zone, area: areaName, score };
            }
          }
        }
      }
    }
  }

  if (bestMatch) {
    result.province = bestMatch.province;
    result.city = bestMatch.city;
    result.zone = bestMatch.zone;
    result.area = bestMatch.area;
    return result;
  }

  // Fallback to matching city/town
  for (const p of ZIMBABWE_LOCATIONS) {
    for (const c of p.cities) {
      const cityBare = c.city.toLowerCase().replace(/\s*\([^)]*\)\s*/g, '').trim();
      if (lower.includes(c.city.toLowerCase()) || (cityBare && lower.includes(cityBare))) {
        result.province = p.province;
        result.city = c.city;
        return result;
      }
    }
  }

  // Fallback to matching province
  for (const p of ZIMBABWE_LOCATIONS) {
    if (lower.includes(p.province.toLowerCase())) {
      result.province = p.province;
      return result;
    }
  }

  return result;
}

export function matchesLocationFilter(listingLocation = '', { province = '', city = '', zone = '', area = '', location = '' } = {}) {
  const rawLower = norm(listingLocation);
  if (!province && !city && !zone && !area && !location) return true;
  if (!rawLower) return false;

  const parsed = parseLocationString(listingLocation);

  if (province) {
    const provMatch = norm(parsed.province) === norm(province) || rawLower.includes(norm(province));
    if (!provMatch) return false;
  }

  if (city) {
    const cityBare = norm(city).replace(/\s*\([^)]*\)\s*/g, '').trim();
    const cityMatch =
      norm(parsed.city) === norm(city) ||
      rawLower.includes(norm(city)) ||
      (cityBare && rawLower.includes(cityBare));
    if (!cityMatch) return false;
  }

  if (zone) {
    const zoneMatch = norm(parsed.zone) === norm(zone);
    if (!zoneMatch) {
      // Check if listing location explicitly contains any area inside that zone
      const zoneAreas = getAreas({ province, city, zone });
      const hitsAreaInZone = zoneAreas.some(item => {
        const bare = norm(item.area).replace(/\s*\([^)]*\)\s*/g, '').trim();
        return rawLower.includes(norm(item.area)) || (bare && rawLower.includes(bare));
      });
      if (!hitsAreaInZone) return false;
    }
  }

  if (area) {
    const areaBare = norm(area).replace(/\s*\([^)]*\)\s*/g, '').trim();
    const areaMatch =
      norm(parsed.area) === norm(area) ||
      rawLower.includes(norm(area)) ||
      (areaBare && rawLower.includes(areaBare));
    if (!areaMatch) return false;
  }

  if (location) {
    const q = norm(location);
    const directMatch = rawLower.includes(q);
    const parsedMatch =
      norm(parsed.province).includes(q) ||
      norm(parsed.city).includes(q) ||
      norm(parsed.zone).includes(q) ||
      norm(parsed.area).includes(q);
    if (!directMatch && !parsedMatch) return false;
  }

  return true;
}
